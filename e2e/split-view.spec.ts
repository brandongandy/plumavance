import { expect, test, type Page } from '@playwright/test'

import { createDocument, createProject } from './helpers.js'

async function expectSplit(page: Page, titles: readonly string[], focusedTitle: string): Promise<void> {
  const tabs = page.getByRole('group', { name: 'Open documents', exact: true })
  await expect(tabs.locator('[data-editor-tab].is-split')).toHaveCount(2)
  await expect(tabs.locator('[data-editor-tab].is-active')).toHaveCount(1)
  await expect(tabs.locator('[data-editor-tab] [aria-pressed="true"]')).toHaveCount(1)
  await expect(page.locator('[data-document-pane]')).toHaveCount(2)
  await expect(page.locator('[data-document-pane].is-focused')).toHaveCount(1)
  for (const title of titles) {
    await expect(tabs.getByRole('button', { name: `${title}, shown in split`, exact: true }))
      .toHaveAttribute('aria-pressed', String(title === focusedTitle))
    await expect(page.getByLabel(`${title} document editor`, { exact: true })).toBeVisible()
    await expect(page.getByLabel(`${title} document editor`, { exact: true })).toBeEditable()
  }
  await expect(page.getByRole('region', { name: `${focusedTitle} pane`, exact: true })).toHaveClass(/is-focused/)
}

test('keeps_split_documents_independent_through_focus_layout_close_and_reload', async ({ page }) => {
  test.setTimeout(60_000)
  await page.setViewportSize({ width: 1440, height: 900 })
  await createProject(page, 'Split Writing Journey')
  for (const title of ['Chapter One', 'Research', 'Chapter Three']) {
    await createDocument(page)
    await page.getByLabel('Document title', { exact: true }).fill(title)
    await page.getByLabel('Save document', { exact: true }).click()
    await expect(page.getByRole('region', { name: `${title} pane`, exact: true }).getByText('Saved', { exact: true })).toBeVisible()
  }
  const tabs = page.getByRole('group', { name: 'Open documents', exact: true })
  const status = page.getByRole('contentinfo')
  await page.getByLabel('Open Chapter One in new tab', { exact: true }).click()
  await page.getByLabel('Open Research in new tab', { exact: true }).click()
  await tabs.getByRole('button', { name: 'Research', exact: true }).click()
  await tabs.getByRole('button', { name: 'Chapter One', exact: true }).click()
  await page.getByLabel('Split editor vertically', { exact: true }).click()
  await expectSplit(page, ['Chapter One', 'Research'], 'Chapter One')
  await expect(page.getByLabel('Split editor vertically', { exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByLabel('Split editor horizontally', { exact: true })).toHaveAttribute('aria-pressed', 'false')

  await page.getByRole('region', { name: 'Chapter One pane', exact: true }).getByLabel('Document title').fill('Opening chapter')
  await page.getByLabel('Opening chapter document editor', { exact: true }).fill('A quiet opening scene.')
  await page.getByLabel('Document notes', { exact: true }).fill('Keep the first voice quiet.')
  await expect(status).toContainText('Opening chapter')
  await expect(status).toContainText('4 words · 22 characters')
  await expect(status).toContainText('Unsaved')

  await page.getByRole('region', { name: 'Research pane', exact: true }).getByLabel('Document title').fill('Research archive')
  await page.getByLabel('Research archive document editor', { exact: true }).fill('Maps and letters.')
  await page.getByLabel('Document notes', { exact: true }).fill('Check the dates separately.')
  await expect(status).toContainText('Research archive')
  await expect(status).toContainText('3 words · 17 characters')
  await page.getByLabel('Save document', { exact: true }).click()
  await expect(page.getByRole('region', { name: 'Research archive pane', exact: true }).getByText('Saved', { exact: true })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Opening chapter pane', exact: true }).getByText('Unsaved', { exact: true })).toBeVisible()
  await page.getByLabel('Opening chapter document editor', { exact: true }).focus()
  await expect(page.getByLabel('Document notes', { exact: true })).toHaveValue('Keep the first voice quiet.')
  await page.keyboard.press('ControlOrMeta+s')
  await expect(page.getByRole('region', { name: 'Opening chapter pane', exact: true }).getByText('Saved', { exact: true })).toBeVisible()
  await expectSplit(page, ['Opening chapter', 'Research archive'], 'Opening chapter')

  await page.getByLabel('Split editor horizontally', { exact: true }).click()
  await expect(page.getByLabel('Split editor vertically', { exact: true })).toHaveAttribute('aria-pressed', 'false')
  await expect(page.getByLabel('Split editor horizontally', { exact: true })).toHaveAttribute('aria-pressed', 'true')
  const divider = page.getByRole('separator', { name: 'Resize split', exact: true })
  await expect(divider).toHaveAttribute('aria-orientation', 'horizontal')
  await expect(divider).toHaveAttribute('aria-valuenow', '50')
  await divider.focus()
  await page.keyboard.press('ArrowDown')
  await expect(divider).toHaveAttribute('aria-valuenow', '55')
  await expectSplit(page, ['Opening chapter', 'Research archive'], 'Opening chapter')

  // Both dirty buffers must survive unmounting the unfocused pane on a phone.
  await page.getByLabel('Opening chapter document editor', { exact: true }).fill('A quiet opening scene. Revised on desktop.')
  await page.getByLabel('Research archive document editor', { exact: true }).fill('Maps and letters. A second source.')
  await page.getByLabel('Document notes', { exact: true }).fill('Check the dates and sources separately.')
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.locator('[data-workspace]')).toHaveAttribute('data-layout', 'phone')
  await expect(page.locator('[data-document-pane]')).toHaveCount(1)
  await expect(page.getByLabel('Research archive document editor', { exact: true })).toHaveText('Maps and letters. A second source.')
  await expect(divider).toHaveCount(0)
  await expect(tabs.locator('[data-editor-tab].is-split')).toHaveCount(2)
  await expect(page.getByLabel('Split editor horizontally', { exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByLabel('Inspector panel', { exact: true }).click()
  await expect(page.getByLabel('Document notes', { exact: true })).toHaveValue('Check the dates and sources separately.')
  await page.getByLabel('Editor panel', { exact: true }).click()
  await page.getByLabel('Research archive document editor', { exact: true }).fill('Maps and letters. A second source. Phone edit.')
  await page.setViewportSize({ width: 1440, height: 900 })
  await expectSplit(page, ['Opening chapter', 'Research archive'], 'Research archive')
  await expect(divider).toHaveAttribute('aria-valuenow', '55')
  await expect(page.getByLabel('Opening chapter document editor', { exact: true })).toHaveText('A quiet opening scene. Revised on desktop.')
  await expect(page.getByLabel('Research archive document editor', { exact: true })).toHaveText('Maps and letters. A second source. Phone edit.')
  await expect(status).toContainText('Research archive')
  await expect(status).toContainText('8 words · 46 characters')
  await page.getByLabel('Save document', { exact: true }).click()
  await expect(page.getByRole('region', { name: 'Research archive pane', exact: true }).getByText('Saved', { exact: true })).toBeVisible()
  await page.getByLabel('Opening chapter document editor', { exact: true }).focus()
  await expect(status).toContainText('Opening chapter')
  await expect(status).toContainText('7 words · 42 characters')
  await expect(status).toContainText('Unsaved')
  await page.getByLabel('Save document', { exact: true }).click()
  await expect(page.getByRole('region', { name: 'Opening chapter pane', exact: true }).getByText('Saved', { exact: true })).toBeVisible()

  await tabs.getByRole('button', { name: 'Chapter Three', exact: true }).click()
  await expectSplit(page, ['Chapter Three', 'Research archive'], 'Chapter Three')
  await expect(page.getByLabel('Opening chapter document editor', { exact: true })).toHaveCount(0)
  await expect(tabs.getByRole('button', { name: 'Opening chapter', exact: true })).toBeVisible()
  await expect(status).toContainText('Chapter Three')
  await expect(status).toContainText('0 words · 0 characters')

  await page.getByLabel('Exit split view', { exact: true }).click()
  await expect(tabs.locator('[data-editor-tab]')).toHaveCount(3)
  await expect(tabs.locator('[data-editor-tab].is-split')).toHaveCount(0)
  await expect(page.locator('[data-document-pane]')).toHaveCount(1)
  await expect(tabs.getByRole('button', { name: 'Chapter Three', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(tabs.getByRole('button', { name: 'Research archive', exact: true })).toBeVisible()
  await expect(page.getByLabel('Exit split view', { exact: true })).toBeDisabled()

  await tabs.getByRole('button', { name: 'Research archive', exact: true }).click()
  await tabs.getByRole('button', { name: 'Opening chapter', exact: true }).click()
  await page.getByLabel('Split editor vertically', { exact: true }).click()
  await expectSplit(page, ['Opening chapter', 'Research archive'], 'Opening chapter')
  await page.getByLabel('Close Research archive', { exact: true }).click()
  await expect(tabs.locator('[data-editor-tab]')).toHaveCount(2)
  await expect(tabs.getByRole('button', { name: /Research archive/ })).toHaveCount(0)
  await expect(tabs.locator('[data-editor-tab].is-split')).toHaveCount(0)
  await expect(page.getByLabel('Exit split view', { exact: true })).toBeDisabled()
  await expect(tabs.getByRole('button', { name: 'Opening chapter', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('[data-document-pane].is-focused')).toHaveCount(1)
  await expect(page.getByLabel('Opening chapter document editor', { exact: true })).toBeVisible()

  await page.reload()
  for (const { title, body, notes } of [
    { title: 'Opening chapter', body: 'A quiet opening scene. Revised on desktop.', notes: 'Keep the first voice quiet.' },
    { title: 'Research archive', body: 'Maps and letters. A second source. Phone edit.', notes: 'Check the dates and sources separately.' },
    { title: 'Chapter Three', body: '', notes: '' },
  ]) {
    await page.getByRole('treeitem', { name: `${title}, document`, exact: true }).click()
    await expect(page.getByLabel('Document title', { exact: true })).toHaveValue(title)
    await expect(page.getByLabel(`${title} document editor`, { exact: true })).toHaveText(body)
    await expect(page.getByLabel('Document notes', { exact: true })).toHaveValue(notes)
    await expect(status).toContainText('Saved')
  }
})
